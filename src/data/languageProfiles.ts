const DEFAULT_SOURCES = [
  'PHOIBLE 2.0 inventory data',
  'WALS Online typological chapters',
  'Compact singing-oriented abstraction; individual languages and dialects vary',
];

function p(
  id: string,
  name: string,
  family: string,
  region: string,
  consonants: string,
  vowels: string,
  prosody: string,
  rhythm: string,
  distinctive: string,
  tags: string[] = [],
  sourceNotes: string[] = DEFAULT_SOURCES,
): LanguageProfile {
  return {
    id: 'lang-' + id,
    name,
    family,
    region,
    consonantFeatures: [consonants],
    vowelFeatures: [vowels],
    prosodyFeatures: [prosody],
    rhythmNotes: [rhythm],
    phonologyNotes: [consonants + ' ' + vowels + ' ' + prosody],
    distinctiveFeatures: [distinctive],
    tags: ['language', ...tags],
    sourceNotes,
  };
}

