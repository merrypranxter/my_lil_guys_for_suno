export function languageProfileToEngine(profile: LanguageProfile): CompositionEngine {
  const consonants = profile.consonantFeatures.join(' ');
  const vowels = profile.vowelFeatures.join(' ');
  const prosody = profile.prosodyFeatures.join(' ');
  const rhythm = profile.rhythmNotes.join(' ');
  const distinctive = profile.distinctiveFeatures.join(' ');

  return {
    id: profile.id,
    domain: 'voice',
    dimension: 'language',
    name: profile.name,
    subtitle: [profile.family, profile.region].filter(Boolean).join(' • '),
    rule:
      'Treat ' + profile.name + ' as a phonological rule system, never as a nationality costume. ' +
      'CONSONANTS: ' + consonants + ' ' +
      'VOWELS: ' + vowels + ' ' +
      'PROSODY: ' + prosody + ' ' +
      'RHYTHM: ' + rhythm + ' ' +
      'DISTINCTIVE CONTROL: ' + distinctive + ' ' +
      'When the selected Language Performance Mode is not native-language singing, transfer only relevant phonological/prosodic tendencies. Do not use comic eye-dialect or personality stereotypes.',
    shortExplanation: distinctive,
    tags: profile.tags,
    accentColor: '#5cf6ff',
    sourceNotes: profile.sourceNotes,
  };
}

export const LANGUAGE_PROFILE_ENGINES: CompositionEngine[] = LANGUAGE_PROFILES.map(languageProfileToEngine);


export function getLanguageProfile(id: string): LanguageProfile | undefined {
  return LANGUAGE_PROFILES.find((profile) => profile.id === id);
}

export function searchLanguageProfiles(query: string): LanguageProfile[] {
  const q = query.trim().toLowerCase();
  if (!q) return LANGUAGE_PROFILES;
  return LANGUAGE_PROFILES.filter((profile) =>
    [
      profile.name,
      profile.family || '',
      profile.region || '',
      ...profile.consonantFeatures,
      ...profile.vowelFeatures,
      ...profile.prosodyFeatures,
      ...profile.rhythmNotes,
      ...profile.distinctiveFeatures,
      ...profile.tags,
    ].join(' ').toLowerCase().includes(q)
  );
}
