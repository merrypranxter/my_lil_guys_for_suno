export const MOUTH_TRAIT_BY_ID = new Map(MOUTH_TRAITS.map((item) => [item.id, item]));

export function getMouthTrait(id: string): MouthTrait | undefined {
  return MOUTH_TRAIT_BY_ID.get(id);
}

export function searchMouthTraits(query: string): MouthTrait[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return MOUTH_TRAITS;

  return MOUTH_TRAITS.filter((item) =>
    [
      item.name,
      item.shortExplanation,
      item.operation,
      ...item.tags,
      ...item.musicalAffordances,
    ]
      .join(' ')
      .toLowerCase()
      .includes(needle),
  );
}
