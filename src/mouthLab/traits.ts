import { MouthTrait } from './types';

const LEDGER = 'docs/LANGUAGE_PHONOLOGY_SOURCE_LEDGER.md';

function trait(
  id: string,
  name: string,
  category: MouthTrait['category'],
  axes: MouthTrait['axes'],
  shortExplanation: string,
  operation: string,
  tags: string[],
  musicalAffordances: string[],
  donorProfileIds: string[],
  defaultPressure: MouthTrait['defaultPressure'] = 'medium',
  confidence: MouthTrait['confidence'] = 'high',
  cautions: string[] = [],
  extraSourceNotes: string[] = [],
): MouthTrait {
  return {
    id,
    name,
    category,
    axes,
    shortExplanation,
    operation,
    tags,
    musicalAffordances,
    donorProfileIds,
    defaultPressure,
    confidence,
    sourceNotes: [
      LEDGER,
      'docs/MOUTH_LAB_SOURCE_LEDGER.md',
      ...donorProfileIds.map((profileId) => 'src/data/languageProfiles.ts#' + profileId),
      ...extraSourceNotes,
    ],
    cautions,
  };
}

